    public ArrayList<Mahasiswa> getMahasiswaList()
    {
       ArrayList<Mahasiswa> mahasiswaList = new ArrayList<Mahasiswa>();
       
       String query = "SELECT * FROM mahasiswa";
       
       Statement st;
       ResultSet rs;
       
       try{
           st = con.createStatement();
           rs = st.executeQuery(query);
           
           Mahasiswa m;           
           while(rs.next()){
               m = new Mahasiswa(rs.getString("npm"), 
                       rs.getString("nama"), rs.getString("prodi"), 
                       rs.getString("status_kelas"), rs.getString("hobi"));
               mahasiswaList.add(m);
           }        
       }catch(Exception e){
           e.printStackTrace();
       }       
       return mahasiswaList;
    }    
    
    public void show_inJtable(){
        
        ArrayList<Mahasiswa> list = getMahasiswaList();
        
        DefaultTableModel model = (DefaultTableModel)tblMahasiswa.getModel();
        
        Object[] row = new Object[5];
        
        for(int i=0; i < list.size(); i++){
            row[0] = list.get(i).getNpm();
            row[1] = list.get(i).getNama();
            row[2] = list.get(i).getProdi();
            row[3] = list.get(i).getStatusKelas();
            row[4] = list.get(i).getHobi();            
            model.addRow(row);
        }       
    }
        
    public void executeSQLQuery(String query, String pesan)
    {
        Statement st;
        
        try{
           st = con.createStatement();
           
           if(st.executeUpdate(query) == 1){
               
               //refresh jtable data
               DefaultTableModel model = (DefaultTableModel)tblMahasiswa.getModel();
               model.setRowCount(0);
               show_inJtable();
               
               JOptionPane.showMessageDialog(null, "Data " + pesan + " Succefully");
           }
           else{
               JOptionPane.showMessageDialog(null, "Data Not " + pesan);           
           }
                 
       }catch(Exception e){
           e.printStackTrace();
       }        
    }
        
    
    
