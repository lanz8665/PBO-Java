    private void tblMahasiswaMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblMahasiswaMouseClicked
        // TODO add your handling code here:
        lblPesan.setText("");
        DefaultTableModel model = (DefaultTableModel) tblMahasiswa.getModel();
        tfNpm.setText(model.getValueAt(tblMahasiswa.getSelectedRow(), 0).toString());
        tfNama.setText(model.getValueAt(tblMahasiswa.getSelectedRow(), 1).toString());
        cbProdi.setSelectedItem(model.getValueAt(tblMahasiswa.getSelectedRow(), 2).toString());        
        String statusKelas = model.getValueAt(tblMahasiswa.getSelectedRow(), 3).toString();
        if(statusKelas.equalsIgnoreCase("Reguler")){
            rbReguler.setSelected(true);
        }else{
            rbKaryawan.setSelected(true);
        }        
        String hobi = model.getValueAt(tblMahasiswa.getSelectedRow(), 4).toString();
        //reset chexbox
        chBaca.setSelected(false);
        chOlahraga.setSelected(false);
        if(hobi.toLowerCase().contains("baca")){
            chBaca.setSelected(true);
        }
        if(hobi.toLowerCase().contains("olahraga")){
            chOlahraga.setSelected(true);
        }        
    }//GEN-LAST:event_tblMahasiswaMouseClicked

