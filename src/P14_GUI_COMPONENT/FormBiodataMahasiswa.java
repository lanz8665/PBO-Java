    private void btnTambahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTambahActionPerformed
        String npm = tfNpm.getText().trim();//menghilangkan spasi pada npm
        String nama = tfNama.getText();
        String prodi = cbProdi.getSelectedItem().toString();
        String statusKelas = rbReguler.isSelected() ? "Reguler": "Karyawan";
        String baca = chBaca.isSelected() ? chBaca.getText() : "";
        String olahraga =  chOlahraga.isSelected()? chOlahraga.getText():"";
        String hobi = baca + " "+olahraga;
        //tambahkan pada table
        DefaultTableModel model = (DefaultTableModel) tblMahasiswa.getModel();

        if(!npm.equals("")){
            boolean sudahAda = false;
            for(int i=0; i<model.getRowCount(); i++){
                String npmExist = model.getValueAt(i, 0).toString();
                if(npm.equalsIgnoreCase(npmExist)){
                    sudahAda = true;
                    break;
                }
            }
            if(sudahAda){
                lblPesan.setText("Tidak dapat ditambahkan! NPM sudah ada.");
            }else{
                //model.addRow(new Object[]{npm, nama, prodi, statusKelas, hobi});  
                String query = "INSERT INTO `mahasiswa`(`npm`, `nama`, `prodi`, `status_kelas`, `hobi`) "
                + "VALUES ('"+npm+"','"+nama+"','"+prodi+"','"+statusKelas+"','"+hobi+"')";
        
                executeSQLQuery(query, "Inserted");                
            }
        }else{
            lblPesan.setText("*NPM tidak boleh kosong!");
        }
    }//GEN-LAST:event_btnTambahActionPerformed

